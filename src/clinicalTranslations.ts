function tidyChinese(value: string) {
  return value
    .replace(/\s+([，。；：、！？])/g, "$1")
    .replace(/([，。；：、！？])\s+/g, "$1")
    .replace(/([\u3400-\u9fff])\s+([\u3400-\u9fff])/g, "$1$2")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+,/g, "，")
    .replace(/,\s*/g, "，")
    .replace(/;\s*/g, "；")
    .replace(/:\s*/g, "：")
    .replace(/\.\s*/g, "。")
    .trim();
}

export function translateClinicalText(value: string, language: Language) {
  if (language === "en" || !value) return value;
  if (exactTranslations[value]) return exactTranslations[value];

  let translated = value;
  for (const [pattern, replacement] of replacements) {
    translated = translated.replace(pattern, replacement);
  }
  return tidyChinese(translated);
}

export function translateClinicalList(values: string[], language: Language) {
  return values.map((value) => translateClinicalText(value, language));
}
