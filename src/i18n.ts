export function localizedSystem(name: string, language: Language) {
  return language === "zh" ? systemNames[name] ?? name : name;
}

export function localizedCondition(
  condition: { courseNumber: number; diseaseName: string },
  language: Language,
) {
  return language === "zh" ? conditionNames[condition.courseNumber] ?? condition.diseaseName : condition.diseaseName;
}
